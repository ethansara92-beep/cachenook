const byId = new Map(TARGETS.map((target) => [target.id, target]));

function getTarget(id) {
  return byId.get(id) || null;
}

async function resolveRoots(target) {
  const roots = target.resolveRoots ? await target.resolveRoots() : target.roots || [];
  return roots;
}

/** Serializable target metadata for the renderer. */
function describeTargets() {
  return TARGETS.map((target) => ({
    id: target.id,
    kind: target.kind || 'directory',
    protected: Boolean(target.protected),
    group: target.group,
    name: target.name,
    icon: target.icon,
    description: target.description,
    risk: target.risk,
    defaultSelected: target.defaultSelected,
    command: target.command || null,
  }));
}

